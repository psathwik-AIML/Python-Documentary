# break 
# used for breaking current iteration 
for i in range (5):
    if(i==3):
        break
    print(i)

# continue 
# used for skipping current iteration 
for i in range (5):
    if(i==3):
        continue
    print(i)

# pass 
# do nothing just a place holder 
for i in range(5):
    pass
    print(i)
    
